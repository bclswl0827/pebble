package main

import (
	"fmt"
	"strings"
)

const bytesPerLine = 11

// The firmware broadcasts a single fixed key: the leading (last) one.
func cHeader(prefix string, keys []keyPair) string {
	leading := keys[len(keys)-1]
	adv := leading.adv
	var builder strings.Builder
	builder.WriteString("#ifndef FINDMY_KEY_H\n#define FINDMY_KEY_H\n\n")
	builder.WriteString("/*\n")
	builder.WriteString(" * OpenHaystack advertisement key: 28 bytes (P-224 public key X coordinate).\n")
	fmt.Fprintf(&builder, " * Generated by tools/findmy-keygen, prefix %s.\n", prefix)
	fmt.Fprintf(&builder, " * Advertisement key: %s\n", leading.advB64)
	fmt.Fprintf(&builder, " * Hashed adv key:    %s\n", leading.hashB64)
	fmt.Fprintf(&builder, " * BLE MAC (random static): %s, from key[0..5]; see\n", macAddress(adv))
	builder.WriteString(" * user_app_generate_static_addr(). Editing the MAC changes the key.\n")
	if len(keys) > 1 {
		fmt.Fprintf(&builder, " * Leading key %d of %d; the firmware does not rotate keys.\n", len(keys), len(keys))
	}
	builder.WriteString(" * The private key stays on the reader side; never put it in the firmware.\n")
	builder.WriteString(" */\n")
	builder.WriteString("#define FINDMY_ADV_KEY { \\\n")
	fmt.Fprintf(&builder, "    /* key[0]: MAC byte 0 (0x%02X | 0xC0 = 0x%02X); bits 7-6 (%d) go to adv_data[29] */ \\\n",
		adv[0], adv[0]|0xC0, adv[0]>>6)
	writeBytes(&builder, adv[:1])
	builder.WriteString("    /* key[1..5]: MAC bytes 1-5, used as-is */ \\\n")
	writeBytes(&builder, adv[1:macLen])
	builder.WriteString("    /* key[6..27]: adv_data[7..28] */ \\\n")
	writeBytes(&builder, adv[macLen:])
	builder.WriteString("}\n\n#endif\n")
	return builder.String()
}

func writeBytes(builder *strings.Builder, data []byte) {
	for offset := 0; offset < len(data); offset += bytesPerLine {
		builder.WriteString("   ")
		for _, value := range data[offset:min(offset+bytesPerLine, len(data))] {
			fmt.Fprintf(builder, " 0x%02X,", value)
		}
		builder.WriteString(" \\\n")
	}
}
